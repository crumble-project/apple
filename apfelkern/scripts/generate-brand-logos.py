#!/usr/bin/env python3
"""Writes Sources/BotAvatar/BrandLogoData.swift from the icon packages the web app bundles.

Reads the provider map in bot/apps/web/features/providers/provider-logos.ts, so a rerun follows the web.
Run `bun install` in bot first.
"""
import glob
import json
import re
import sys
from pathlib import Path

APPLE = Path(__file__).resolve().parents[2]
BOT = APPLE.parent / "bot"
OUTPUT = APPLE / "apfelkern/Sources/BotAvatar/BrandLogoData.swift"
# What gateway-brand.tsx and password-managers.tsx take from Simple Icons.
SIMPLE = {"gateway:discord": "Discord", "manager:1password": "1Password", "manager:bitwarden": "Bitwarden"}


def package(pattern):
    found = glob.glob(str(BOT / "node_modules/.bun" / pattern))
    if not found:
        sys.exit(f"Missing {pattern}: run bun install in bot")
    return Path(found[0])


def dark(hex_color):
    r, g, b = (int(hex_color[at : at + 2], 16) / 255 for at in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b < 0.2


def simple_icon(root, title):
    icons = json.loads((root / "data/simple-icons.json").read_text())
    icon = next(item for item in icons if item["title"] == title)
    slug = icon.get("slug") or re.sub(r"[^a-z0-9]", "", title.lower())
    path = re.search(r' d="([^"]+)"', (root / f"icons/{slug}.svg").read_text()).group(1)
    # As on the web: near-black marks would vanish on a dark background, so they take the text color.
    fill = "currentColor" if dark(icon["hex"]) else f"#{icon['hex']}"
    return f'<svg viewBox="0 0 24 24"><path d="{path}" fill="{fill}"/></svg>'


def provider_logos(icons):
    source = (BOT / "apps/web/features/providers/provider-logos.ts").read_text()
    files = dict(re.findall(r'import (\w+) from "@lobehub/icons-static-svg/icons/([\w-]+\.svg)"', source))
    table = re.search(r"const LOGOS = \{(.*?)\} satisfies", source, re.S).group(1)
    logos = {}
    for key, name in re.findall(r'^\s*"?([\w-]+)"?: (\w+),$', table, re.M):
        logos[f"provider:{key}"] = (icons / files[name]).read_text().strip()
    return logos


def main():
    icons = package("@lobehub+icons-static-svg@*/node_modules/@lobehub/icons-static-svg/icons")
    simple = package("simple-icons@*/node_modules/simple-icons")
    logos = provider_logos(icons) | {key: simple_icon(simple, title) for key, title in SIMPLE.items()}
    lines = [
        "// Generated by apfelkern/scripts/generate-brand-logos.py. Do not edit.",
        "// LobeHub Icons (MIT) and Simple Icons (CC0 1.0); see THIRD_PARTY_NOTICES.md.",
        "",
        "// swiftlint:disable line_length file_length",
        "enum BrandLogoData {",
        "  static let markup: [String: String] = [",
    ]
    for key in sorted(logos):
        lines.append(f'    "{key}": ##"{logos[key]}"##,')
    lines += ["  ]", "}", ""]
    OUTPUT.write_text("\n".join(lines))
    print(f"{len(logos)} logos")


main()
